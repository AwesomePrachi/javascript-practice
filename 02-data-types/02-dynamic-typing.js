// Dynamic Typing

// JavaScript is dynamically typed.
// A variable is not permanently associated with one data type.
// The same variable can hold values of different types.

let value = 12;

console.log(value); // 12
console.log(typeof value); // "number"

value = "Prachi";

console.log(value); // "Prachi"
console.log(typeof value); // "string"

value = true;

console.log(value); // true
console.log(typeof value); // "boolean"

value = null;

console.log(value); // null
console.log(typeof value); // "object"

// The variable "value" was reassigned to values
// of different types during the program.