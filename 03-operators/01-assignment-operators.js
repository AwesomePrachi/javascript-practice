// Assignment Operators

// Assignment operators assign a value to a variable
// or update the value of an existing variable.

// =
// +=
// -=
// *=
// /=
// %=
// **=


// Assignment (=)

let score = 12;

console.log(score); // 12


// Addition Assignment (+=)

score += 2;

console.log(score); // 14

// Same as:
// score = score + 2;


// Subtraction Assignment (-=)

score -= 2;

console.log(score); // 12

// Same as:
// score = score - 2;


// Multiplication Assignment (*=)

score *= 3;

console.log(score); // 36

// Same as:
// score = score * 3;


// Division Assignment (/=)

score /= 4;

console.log(score); // 9

// Same as:
// score = score / 4;


// Remainder Assignment (%=)

score %= 3;

console.log(score); // 0

// Same as:
// score = score % 3;


// Exponentiation Assignment (**=)

let number = 2;

number **= 3;

console.log(number); // 8

// Same as:
// number = number ** 3;