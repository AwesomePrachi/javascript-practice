    // Arithmetic Operators

// Arithmetic operators are used to perform calculations.

// +
// -
// *
// /
// %
// **


// Addition (+)

console.log(2 + 2); // 4


// String Concatenation (+)

console.log("Prachi" + " Patel"); // "Prachi Patel"

// The + operator can also concatenate strings.


// Subtraction (-)

console.log(6 - 4); // 2


// Multiplication (*)

console.log(2 * 12); // 24


// Division (/)

console.log(9 / 3); // 3


// Remainder (%)

console.log(12 % 3); // 0

console.log(10 % 3); // 1

// % returns the remainder after division.


// Exponentiation (**)

console.log(2 ** 3); // 8

// 2 raised to the power of 3.